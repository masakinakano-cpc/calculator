/**
 * テーマに応じたテキストを取得
 */
export function getThemeText(theme: Theme, key: keyof typeof TEXT_MAPPING.kids): string {
    return TEXT_MAPPING[theme][key] || TEXT_MAPPING.kids[key];
}

/**
 * 現在のテーマに応じたテキストを取得（React用）
 */
export function useThemeText(theme: Theme | null | undefined) {
    const currentTheme: Theme = theme || 'kids';
    return (key: keyof typeof TEXT_MAPPING.kids): string => {
        return getThemeText(currentTheme, key);
    };
}
